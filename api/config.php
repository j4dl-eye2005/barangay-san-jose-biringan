<?php
declare(strict_types=1);

/** Resolve the application’s protected data directory beside the public web root. */
function portalPrivateDataRoot(): string
{
    $documentRoot = realpath((string) ($_SERVER['DOCUMENT_ROOT'] ?? ''));
    $base = $documentRoot !== false ? dirname($documentRoot) : dirname(__DIR__, 2);
    if ($documentRoot === false
        && in_array(strtolower(basename(str_replace('\\', '/', $base))), ['htdocs', 'public_html', 'www', 'wwwroot'], true)) {
        $base = dirname($base);
    }
    return rtrim($base, DIRECTORY_SEPARATOR) . DIRECTORY_SEPARATOR . 'barangay_portal_private';
}

/** Load deployment secrets from an env file outside the web root when needed. */
function loadPortalEnvFile(): void
{
    static $loaded = false;
    if ($loaded) return;
    $loaded = true;
    $configuredEnvFile = trim((string) ($_ENV['PORTAL_ENV_FILE'] ?? getenv('PORTAL_ENV_FILE') ?: ''));
    if ($configuredEnvFile !== ''
        && !str_starts_with($configuredEnvFile, DIRECTORY_SEPARATOR)
        && !preg_match('/^[A-Za-z]:[\\\\\/]/', $configuredEnvFile)) {
        error_log('PORTAL_ENV_FILE must be an absolute path outside the web root.');
        return;
    }
    $envFile = $configuredEnvFile !== ''
        ? $configuredEnvFile
        : portalPrivateDataRoot() . DIRECTORY_SEPARATOR . '.env';
    $realEnvFile = realpath($envFile);
    if ($realEnvFile === false || !is_file($realEnvFile)) return;
    $documentRoot = realpath((string) ($_SERVER['DOCUMENT_ROOT'] ?? ''));
    $applicationRoot = realpath(dirname(__DIR__));
    $isWithin = static function (string $candidate, string $root): bool {
        $candidate = rtrim(str_replace('\\', '/', $candidate), '/');
        $root = rtrim(str_replace('\\', '/', $root), '/');
        return strcasecmp($candidate, $root) === 0
            || strncasecmp($candidate, $root . '/', strlen($root) + 1) === 0;
    };
    if (($documentRoot !== false && $isWithin($realEnvFile, $documentRoot))
        || ($applicationRoot !== false && $isWithin($realEnvFile, $applicationRoot))) {
        error_log('PORTAL_ENV_FILE must be outside the application and web roots.');
        return;
    }
    $lines = file($realEnvFile, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES);
    if (!is_array($lines)) return;
    foreach ($lines as $line) {
        $line = trim($line);
        if ($line === '' || $line[0] === '#' || !str_contains($line, '=')) continue;
        [$name, $value] = explode('=', $line, 2);
        $name = trim($name);
        $value = trim($value);
        if (!preg_match('/^[A-Z][A-Z0-9_]*$/', $name)) continue;
        if (strlen($value) >= 2 && (($value[0] === '"' && substr($value, -1) === '"') || ($value[0] === "'" && substr($value, -1) === "'"))) {
            $value = substr($value, 1, -1);
        }
        // Store in $_ENV directly so this works even when putenv() is disabled
        // (e.g. InfinityFree shared hosting). Only set if not already present
        // so real environment variables still take precedence.
        if (!isset($_ENV[$name])) {
            $_ENV[$name] = $value;
        }
        // Attempt putenv() as well for hosts that do support it; ignore failure.
        @putenv($name . '=' . $value);
    }
}

function portalConfig(): array
{
    loadPortalEnvFile();
    // Read from $_ENV first (works even when putenv() is disabled on shared
    // hosts like InfinityFree), then fall back to getenv() for environments
    // that set variables through server config rather than a .env file.
    $env = static fn(string $key): string => trim((string) ($_ENV[$key] ?? getenv($key) ?: ''));
    $appUrl = $env('APP_URL');
    $privateStorage = $env('APP_PRIVATE_STORAGE');
    if ($privateStorage === '') {
        $privateStorage = portalPrivateDataRoot() . DIRECTORY_SEPARATOR . 'storage';
    } elseif (!str_starts_with($privateStorage, DIRECTORY_SEPARATOR)
        && !preg_match('/^[A-Za-z]:[\\\\\/]/', $privateStorage)) {
        // Relative paths are resolved from the application root, which lets
        // restricted hosts use a protected folder inside their htdocs tree.
        $privateStorage = dirname(__DIR__) . DIRECTORY_SEPARATOR . $privateStorage;
    }
    $requestHost = strtolower((string) ($_SERVER['HTTP_HOST'] ?? ''));
    // Local requests use the XAMPP database in db.php. Keep links generated by
    // those requests on the same local installation even when the private
    // deployment .env contains the public production APP_URL.
    if (preg_match('/^(localhost|127\.0\.0\.1|\[::1\])(?::\d{1,5})?$/', $requestHost)) {
        $scriptName = str_replace('\\', '/', (string) ($_SERVER['SCRIPT_NAME'] ?? ''));
        $appPath = dirname(dirname($scriptName));
        $appPath = $appPath === '.' || $appPath === '/' ? '' : '/' . trim($appPath, '/');
        $scheme = !empty($_SERVER['HTTPS']) && strtolower((string) $_SERVER['HTTPS']) !== 'off' ? 'https' : 'http';
        $appUrl = $scheme . '://' . $requestHost . $appPath;
    }
    return [
        'db_host'         => $env('DB_HOST'),
        'db_port'         => $env('DB_PORT') ?: '3306',
        'db_name'         => $env('DB_NAME'),
        'db_user'         => $env('DB_USER'),
        'db_password'     => $env('DB_PASS'),
        'smtp_host'       => $env('SMTP_HOST'),
        'smtp_port'       => $env('SMTP_PORT') ?: '587',
        'smtp_username'   => $env('SMTP_USERNAME'),
        'smtp_password'   => $env('SMTP_PASSWORD'),
        'smtp_encryption' => strtolower($env('SMTP_ENCRYPTION') ?: 'tls'),
        'from_email'      => $env('MAIL_FROM_EMAIL'),
        'from_name'       => $env('MAIL_FROM_NAME') ?: 'Barangay San Jose',
        'recaptcha_site_key' => $env('RECAPTCHA_SITE_KEY'),
        'recaptcha_secret' => $env('RECAPTCHA_SECRET_KEY'),
        'admin_entry_key' => $env('ADMIN_ENTRY_KEY'),
        'admin_mfa_encryption_key' => $env('ADMIN_MFA_ENCRYPTION_KEY'),
        'app_url' => rtrim($appUrl, '/'),
        // Keep default uploads outside the Apache document root (htdocs).
        'private_storage' => rtrim($privateStorage, DIRECTORY_SEPARATOR),
    ];
}

/** CAPTCHA may be skipped only when explicitly enabled on a local server. */
function portalLocalCaptchaBypass(): bool
{
    loadPortalEnvFile();
    // Set this to false to require CAPTCHA during local development.
    // This flag alone is insufficient: both the host and client must be loopback.
    $enabled = true;
    if (isset($_ENV['RECAPTCHA_LOCAL_BYPASS']) || getenv('RECAPTCHA_LOCAL_BYPASS') !== false) {
        $setting = strtolower(trim((string) ($_ENV['RECAPTCHA_LOCAL_BYPASS'] ?? getenv('RECAPTCHA_LOCAL_BYPASS'))));
        $enabled = in_array($setting, ['1', 'true', 'yes', 'on'], true);
    }
    $host = strtolower((string) ($_SERVER['HTTP_HOST'] ?? ''));
    $remoteAddress = (string) ($_SERVER['REMOTE_ADDR'] ?? '');
    $isLocalHost = (bool) preg_match('/^(localhost|127\.0\.0\.1|\[::1\])(?::\d{1,5})?$/', $host);
    $isLocalClient = in_array($remoteAddress, ['127.0.0.1', '::1'], true);
    return $enabled && $isLocalHost && $isLocalClient;
}
